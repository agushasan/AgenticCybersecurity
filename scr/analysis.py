#  11. Maneuvering example: tracking + maneuvering performance                 #
# ============================================================================ #
def fig_route_performance(res, model, attack_start=None, fname=None):
    """
    Three stacked panels sharing a time axis:
      (a) cross-track TRACKING error  δE − E_ref  (trajectory-tracking quality),
      (b) heading δψ and rudder δ — the maneuvering effort through the bends,
      (c) attack-isolation strip.
    """
    fig = plt.figure(figsize=(11.4, 8.8))
    gs = GridSpec(3, 1, figure=fig, hspace=0.16, height_ratios=[1.1, 1.0, 1.4])
    ax1 = fig.add_subplot(gs[0]); ax2 = fig.add_subplot(gs[1], sharex=ax1)
    ax3 = fig.add_subplot(gs[2], sharex=ax1)
    DEG = 180 / np.pi

    # (a) tracking error
    for c in ("truth", "naive", "secure"):
        if c in res.x_true:
            te = res.x_true[c][:, 1] - res.E_ref
            ax1.plot(res.t, te, color=S.ROLE[c], lw=1.9, label=S.LABEL[c])
    if attack_start is not None:
        S.event_marker(ax1, attack_start, "attack", align="left")
    ax1.axhline(0, color=P["subtle"], lw=0.8)
    ax1.set_ylabel("tracking error\nδE − E$_{ref}$  [m]")
    S.style_legend(ax1, loc="lower left", ncol=3, fontsize=9.0)
    S.panel_label(ax1, "a")
    plt.setp(ax1.get_xticklabels(), visible=False)

    # (b) heading & rudder (maneuvering effort) for the secure vessel
    conf = "secure" if "secure" in res.x_true else "truth"
    ax2.plot(res.t, res.psi_ref * DEG, color=P["subtle"], lw=1.4, ls="--",
             label="reference heading ψ$_{ref}$")
    ax2.plot(res.t, res.x_true[conf][:, 2] * DEG, color=P["secure"], lw=1.8,
             label="actual heading δψ (secure)")
    ax2b = ax2.twinx()
    ax2b.plot(res.t, res.u[conf][:, 1] * DEG, color=P["gold"], lw=1.3, alpha=0.8,
              label="rudder δ")
    ax2b.set_ylabel("rudder δ  [deg]", color=P["gold"])
    ax2b.tick_params(axis="y", colors=P["gold"]); ax2b.grid(False)
    if attack_start is not None:
        ax2.axvline(attack_start, color=P["attack"], ls="--", lw=1.2, alpha=0.8)
    ax2.set_ylabel("heading  [deg]")
    S.style_legend(ax2, loc="upper left", fontsize=9.0)
    ax2b.legend(loc="upper right", fontsize=9.0, framealpha=0.95)
    S.panel_label(ax2, "b")
    plt.setp(ax2.get_xticklabels(), visible=False)

    # (c) detection strip
    if res.attacked is not None:
        _detection_strip_into(ax3, res, model, attack_start or res.t[-1] + 1)
        ax3.set_title("")
    S.panel_label(ax3, "c")
    ax3.set_xlabel("time  [s]")
    return S.finalize(fig, fname)


# ============================================================================ #
#  12. Runtime-assurance (M1) demonstration                                    #
# ============================================================================ #
def fig_rta(resC_off, resC_on, e_max, scen_peaks, attack_start=120.0,
            fname=None):
    """
    Two panels:
      (a) Scenario C cross-track with vs without the runtime-assurance filter;
          the fail-safe-engaged interval is shaded.  Without RTA the hull runs
          away across the safe bound; with RTA it is held inside it.
      (b) peak cross-track excursion per scenario, with vs without RTA, against
          the safe bound — RTA contains every case.
    """
    fig, (axa, axb) = plt.subplots(1, 2, figsize=(13.0, 4.8),
                                   gridspec_kw=dict(width_ratios=[1.25, 1]))
    t = resC_off.t
    eoff = resC_off.x_true["secure"][:, 1]
    eon = resC_on.x_true["secure"][:, 1]
    # safe band + hazard
    axa.axhspan(-e_max, e_max, color=P["secure"], alpha=0.07, lw=0)
    axa.axhline(e_max, color=P["hazard"], lw=1.3, ls="--")
    axa.axhline(-e_max, color=P["hazard"], lw=1.3, ls="--", label="safe bound ±e$_{max}$")
    # fail-safe shading
    mode = resC_on.rta_mode["secure"]
    fs = mode == 2
    if np.any(fs):
        idx = np.where(fs)[0]
        axa.axvspan(t[idx[0]], t[idx[-1]], color=P["gold"], alpha=0.14, lw=0,
                    label="fail-safe engaged")
    axa.plot(t, eoff, color=P["naive"], lw=2.0, label="without RTA (runaway)")
    axa.plot(t, eon, color=P["secure"], lw=2.0, label="with RTA (bounded)")
    S.event_marker(axa, attack_start, "attack", align="left")
    axa.set_xlabel("time  [s]"); axa.set_ylabel("true cross-track δE  [m]")
    axa.set_title("Scenario C — all cross-track anchors spoofed", fontsize=11.5)
    axa.set_ylim(min(-e_max * 1.15, eoff.min() * 1.1), e_max * 1.15)
    S.style_legend(axa, loc="lower left", fontsize=8.6)
    S.panel_label(axa, "a")

    # panel b
    scen = list(scen_peaks.keys())
    off = [scen_peaks[s][0] for s in scen]
    on = [scen_peaks[s][1] for s in scen]
    x = np.arange(len(scen)); w = 0.38
    axb.bar(x - w/2, off, w, color=P["naive"], label="without RTA",
            edgecolor="white", lw=1.0)
    axb.bar(x + w/2, on, w, color=P["secure"], label="with RTA",
            edgecolor="white", lw=1.0)
    axb.axhline(e_max, color=P["hazard"], lw=1.3, ls="--", label="safe bound")
    axb.set_xticks(x); axb.set_xticklabels(scen, fontsize=9.5)
    axb.set_ylabel("peak cross-track excursion  [m]")
    axb.set_title("Containment across scenarios", fontsize=11.5)
    axb.set_ylim(0, max(off) * 1.12)
    S.style_legend(axb, loc="upper left", fontsize=9.6)
    S.panel_label(axb, "b")
    return S.finalize(fig, fname)


