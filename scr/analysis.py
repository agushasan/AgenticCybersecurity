#  6. Sensor streams                                                           #
# ============================================================================ #
def fig_sensor_streams(res, model, channels, attack_start=120.0, fname=None,
                       title=None):
    nch = len(channels)
    fig, axes = plt.subplots(nch, 1, figsize=(8.8, 1.55 * nch + 0.8),
                             sharex=True)
    if nch == 1:
        axes = [axes]
    for ax, i in zip(axes, channels):
        ax.plot(res.t, res.y_clean[:, i], color=P["truth"], lw=1.1,
                label="authentic", alpha=0.85)
        ax.plot(res.t, res.y_att[:, i], color=P["naive"], lw=1.4,
                label="received (spoofed)")
        ax.fill_between(res.t, res.y_clean[:, i], res.y_att[:, i],
                        color=P["naive"], alpha=0.12, lw=0)
        ax.axvline(attack_start, color=P["attack"], ls="--", lw=1.0, alpha=0.8)
        ax.set_ylabel(model.names[i], fontsize=10.0)
        ax.legend(loc="upper left", fontsize=8.6, ncol=2, framealpha=0.9)
    axes[-1].set_xlabel("time  [s]")
    if title:
        axes[0].set_title(title)
    return S.finalize(fig, fname)


