#  1. "Ghost-ship" bird's-eye                                                  #
# ============================================================================ #
def fig_birdseye(res, model, hazard_E=90.0, attack_start=120.0, fname=None,
                 title=None, focus="naive"):
    """
    Bird's-eye transit.  Shows the TRUE track (time-coloured) and, for the naive
    filter, the position the autopilot BELIEVES it holds (the 'ghost'): the ship
    is steered to keep the ghost on the centreline while the real hull is dragged
    toward the hazard.  The deception is the shaded gap between them.
    """
    fig, ax = plt.subplots(figsize=(6.8, 7.4))

    # channel corridor + hazard
    S.hazard_corridor(ax, hazard_E, orientation="v", extent=500)
    ax.axvline(0, color=P["subtle"], ls=(0, (6, 4)), lw=1.1, label="Intended track")

    # secure true track (safe)
    if "secure" in res.x_true:
        Ns, Es = _true_track(res, model, "secure")
        ax.plot(Es, Ns, color=P["secure"], lw=2.6, label="Secure: true hull track",
                zorder=4, solid_capstyle="round")

    # naive: true hull (time-coloured) + believed ghost + deception fill
    Nn, En = _true_track(res, model, "naive")
    Nb, Eb = _believed_track(res, model, "naive")
    ax.fill_betweenx(Nn, En, Eb, color=P["naive"], alpha=0.12, lw=0, zorder=2)
    lc = S.time_colored_line(ax, En, Nn, res.t, cmap=S.CMAP_TIME, lw=3.0, zorder=5)
    ax.plot(Eb, Nb, color=P["believed"], lw=1.6, ls=(0, (2, 2)), zorder=4,
            label="Naive: believed position (ghost)")

    # start / end / attack-onset markers
    ax.scatter([En[0]], [Nn[0]], s=55, color=P["ink"], zorder=7, marker="o",
               edgecolor="white", linewidth=1.2, label="Transit start")
    ax.scatter([En[-1]], [Nn[-1]], s=120, color=P["naive"], zorder=7, marker="X",
               edgecolor="white", linewidth=1.4, label="Naive: final hull position")
    ka = int(attack_start / model.p.dt)
    if ka < len(En):
        ax.scatter([En[ka]], [Nn[ka]], s=70, color=P["attack"], zorder=7,
                   marker="D", edgecolor="white", linewidth=1.2)
        ax.annotate("attack\nonset", xy=(En[ka], Nn[ka]),
                    xytext=(26, -4), textcoords="offset points",
                    fontsize=8.3, color=P["attack"], fontweight="bold",
                    ha="left", va="center",
                    arrowprops=dict(arrowstyle="->", color=P["attack"], lw=1.2))

    # annotate the deception gap with a double-headed arrow at a clear height
    gap = np.abs(En - Eb)
    kg = int(0.80 * (len(En) - 1))           # ~80% along-track: large gap, clear space
    if gap[kg] > 15:
        ax.annotate("", xy=(En[kg], Nn[kg]), xytext=(Eb[kg], Nn[kg]),
                    arrowprops=dict(arrowstyle="<->", color=P["naive"], lw=1.6))
        ax.annotate(f"deception gap\n≈ {gap[int(np.argmax(gap))]:.0f} m",
                    xy=((En[kg] + Eb[kg]) / 2, Nn[kg]),
                    xytext=(0, -34), textcoords="offset points",
                    fontsize=8.4, color=P["naive"], fontweight="bold",
                    ha="center", va="center",
                    bbox=dict(boxstyle="round,pad=0.3", fc="white",
                              ec=P["naive"], lw=0.9))

    cbar = fig.colorbar(lc, ax=ax, fraction=0.035, pad=0.02)
    cbar.set_label("time  [s]", fontsize=8.6)
    cbar.ax.tick_params(labelsize=8)

    xmax = max(hazard_E + 30, 1.12 * max(abs(En.min()), abs(En.max()),
                                         abs(Es).max() if "secure" in res.x_true else 0))
    ax.set_xlim(-xmax, xmax)
    ax.set_xlabel("cross-track East deviation  δE  [m]")
    ax.set_ylabel("along-track distance travelled  [m]")
    if title:
        ax.set_title(title)
    S.style_legend(ax, loc="upper right", fontsize=9.5)
    return S.finalize(fig, fname)


# ============================================================================ #
#  2. Per-scenario 4-panel dashboard                                           #
# ============================================================================ #
def fig_dashboard(res, model, hazard_E=90.0, attack_start=120.0, fname=None,
                  suptitle=None, phase_spans=None):
    fig = plt.figure(figsize=(13.6, 8.4))
    gs = GridSpec(2, 2, figure=fig, hspace=0.36, wspace=0.30,
                  height_ratios=[1, 1])

    # (a) cross-track error vs time
    axa = fig.add_subplot(gs[0, 0])
    for c in ("truth", "naive", "secure"):
        if c in res.x_true:
            axa.plot(res.t, res.x_true[c][:, 1], color=S.ROLE[c], lw=2.0,
                     label=S.LABEL[c], zorder=3)
    S.hazard_corridor(axa, hazard_E, orientation="h", extent=400)
    _mark_phases(axa, phase_spans, attack_start)
    axa.set_xlabel("time  [s]"); axa.set_ylabel("true cross-track  δE  [m]")
    axa.set_title("Operational consequence", fontsize=11.5)
    axa.set_ylim(-1.25 * hazard_E, 1.25 * hazard_E)
    S.style_legend(axa, loc="lower left", fontsize=9.6)
    S.panel_label(axa, "a")

    # (b) estimation error vs time (log)
    axb = fig.add_subplot(gs[0, 1])
    for c in ("naive", "secure"):
        if c in res.x_true:
            err = np.abs(res.x_hat[c][:, 1] - res.x_true[c][:, 1])
            axb.plot(res.t, np.maximum(err, 1e-2), color=S.ROLE[c], lw=1.9,
                     label=f"{S.LABEL[c]}")
    _mark_phases(axb, phase_spans, attack_start)
    axb.set_yscale("log")
    axb.set_xlabel("time  [s]")
    axb.set_ylabel("|cross-track est. error|  [m]")
    axb.set_title("Cross-track estimation error", fontsize=11.5)
    S.style_legend(axb, loc="upper left", fontsize=9.6)
    S.panel_label(axb, "b")

    # (c) normalised residual heatmap (secure, all-sensors hypothesis)
    axc = fig.add_subplot(gs[1, 0])
    _residual_heatmap_into(axc, res, model, attack_start)
    S.panel_label(axc, "c")

    # (d) attack-isolation decisions vs ground truth
    axd = fig.add_subplot(gs[1, 1])
    _detection_strip_into(axd, res, model, attack_start, yright=True)
    S.panel_label(axd, "d", dx=0.0)

    if suptitle:
        fig.suptitle(suptitle, fontsize=13.5, fontweight="bold", y=0.985)
    return S.finalize(fig, fname)


def _mark_phases(ax, phase_spans, attack_start):
    if phase_spans:
        for (t0, t1, lab, col) in phase_spans:
            S.shade_phase(ax, t0, t1, color=col, alpha=0.13)
    else:
        ax.axvline(attack_start, color=P["attack"], ls="--", lw=1.3, alpha=0.9)


# ============================================================================ #
#  3. Residual heatmap                                                         #
# ============================================================================ #
def _residual_heatmap_into(ax, res, model, attack_start):
    tr = res.smt_trace
    R = tr["R"]; env = tr["env"]
    ratio = R / np.where(env > 0, env, np.nan)
    with np.errstate(invalid="ignore"):
        logr = np.log10(np.clip(ratio, 1e-2, 1e3)).T   # p x T
    im = ax.imshow(logr, aspect="auto", cmap=S.CMAP_RESID, vmin=-2, vmax=3,
                   extent=[res.t[0], res.t[-1], model.psensors - 0.5, -0.5],
                   interpolation="nearest")
    ax.set_yticks(range(model.psensors))
    ax.set_yticklabels(model.names, fontsize=9.2)
    ax.axvline(attack_start, color=P["ink"], ls="--", lw=1.0, alpha=0.7)
    ax.set_xlabel("time  [s]")
    ax.set_title("Normalised residual  $R_i/\\mathrm{env}_i$  (log$_{10}$)",
                 fontsize=11.5)
    ax.grid(False)
    cb = ax.figure.colorbar(im, ax=ax, fraction=0.030, pad=0.03,
                            ticks=[-2, 0, 2])
    cb.ax.set_yticklabels(["below", "thresh.", "above"], fontsize=8.6)
    cb.ax.tick_params(length=0)
    return im


def fig_residual_heatmap(res, model, attack_start=120.0, fname=None, title=None):
    fig, ax = plt.subplots(figsize=(8.8, 4.6))
    _residual_heatmap_into(ax, res, model, attack_start)
    if title:
        ax.set_title(title)
    return S.finalize(fig, fname)


# ============================================================================ #
#  4. Detection strip (isolation decisions vs ground truth)                    #
# ============================================================================ #
def _detection_strip_into(ax, res, model, attack_start, yright=False):
    p = model.psensors; t = res.t
    dec = res.attacked.astype(float); truth = res.attack_truth.astype(float)
    dt = t[1] - t[0]
    for i in range(p):
        # ground-truth attacked intervals (light band)
        _bands(ax, t, truth[:, i] > 0, i, dt, color=P["attack"], alpha=0.30,
               h=0.42)
        # detected intervals (solid)
        _bands(ax, t, dec[:, i] > 0, i, dt, color=P["hazard"], alpha=0.95,
               h=0.26)
    ax.axvline(attack_start, color=P["ink"], ls="--", lw=1.0, alpha=0.6)
    ax.set_yticks(range(p)); ax.set_yticklabels(model.names, fontsize=9.2)
    if yright:
        ax.yaxis.tick_right()
    ax.set_ylim(p - 0.5, -0.5); ax.set_xlim(t[0], t[-1])
    ax.set_xlabel("time  [s]")
    ax.set_title("Attack isolation: detected vs ground truth", fontsize=11.5)
    ax.grid(False)
    leg = [Patch(fc=P["attack"], alpha=0.30, label="ground-truth attacked"),
           Patch(fc=P["hazard"], alpha=0.95, label="flagged by estimator")]
    ax.legend(handles=leg, loc="upper right", fontsize=9.6, framealpha=0.95)


def _bands(ax, t, mask, row, dt, color, alpha, h):
    """Draw horizontal bars where mask is True, centred on `row`."""
    if not np.any(mask):
        return
    idx = np.where(mask)[0]
    # group consecutive
    splits = np.where(np.diff(idx) > 1)[0] + 1
    for grp in np.split(idx, splits):
        x0 = t[grp[0]] - dt / 2; w = (grp[-1] - grp[0] + 1) * dt
        ax.add_patch(Rectangle((x0, row - h), w, 2 * h, color=color,
                               alpha=alpha, lw=0, zorder=3))


def fig_detection_strip(res, model, attack_start=120.0, fname=None, title=None):
    fig, ax = plt.subplots(figsize=(9.2, 4.6))
    _detection_strip_into(ax, res, model, attack_start)
    if title:
        ax.set_title(title)
    return S.finalize(fig, fname)


# ============================================================================ #
#  5. Dynamic-campaign timeline (phases + detection + impact)                  #
# ============================================================================ #
def fig_campaign(res, model, phases, attack_start, fname=None, title=None):
    """
    Three stacked panels sharing a time axis:
      (a) true cross-track error with phase shading,
      (b) attack-isolation strip (ground truth vs detected),
      (c) count of channels: truly attacked vs flagged.
    """
    fig = plt.figure(figsize=(11.6, 8.6))
    gs = GridSpec(3, 1, figure=fig, hspace=0.12, height_ratios=[1.0, 1.5, 0.7])
    ax1 = fig.add_subplot(gs[0]); ax2 = fig.add_subplot(gs[1], sharex=ax1)
    ax3 = fig.add_subplot(gs[2], sharex=ax1)

    # phase shading across all panels; phase labels INSIDE panel (a)
    for (t0, t1, lab, col) in phases:
        for ax in (ax1, ax2, ax3):
            S.shade_phase(ax, t0, t1, color=col, alpha=0.16)
        ax1.annotate(lab, xy=((t0 + t1) / 2, 0.93), xycoords=("data", "axes fraction"),
                     ha="center", va="top", fontsize=9.2, fontweight="bold",
                     color=col,
                     bbox=dict(boxstyle="round,pad=0.2", fc="white", ec=col,
                               lw=0.8, alpha=0.9))

    # (a) cross-track
    for c in ("truth", "naive", "secure"):
        if c in res.x_true:
            ax1.plot(res.t, res.x_true[c][:, 1], color=S.ROLE[c], lw=1.9,
                     label=S.LABEL[c])
    ax1.set_ylabel("true cross-track δE  [m]")
    if title:
        ax1.set_title(title, pad=12)
    S.style_legend(ax1, loc="lower left", fontsize=9.0, ncol=3)
    S.panel_label(ax1, "a")
    plt.setp(ax1.get_xticklabels(), visible=False)

    # (b) isolation strip
    _detection_strip_into(ax2, res, model, attack_start)
    ax2.set_title(""); ax2.set_xlabel("")
    S.panel_label(ax2, "b")
    plt.setp(ax2.get_xticklabels(), visible=False)

    # (c) channel counts
    n_true = res.attack_truth.sum(axis=1)
    n_det = res.attacked.sum(axis=1)
    ax3.fill_between(res.t, 0, n_true, color=P["attack"], alpha=0.30, step="mid",
                     label="# truly attacked")
    ax3.step(res.t, n_det, color=P["hazard"], lw=1.6, where="mid",
             label="# flagged")
    ax3.set_ylabel("channels"); ax3.set_xlabel("time  [s]")
    ax3.set_ylim(-0.2, max(n_true.max(), n_det.max()) + 0.8)
    S.style_legend(ax3, loc="upper left", fontsize=9.2, ncol=2)
    S.panel_label(ax3, "c")
    return S.finalize(fig, fname)


