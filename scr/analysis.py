# ============================================================================ #
#  Metrics                                                                     #
# ============================================================================ #
def compute_metrics(res, attack_start=120.0, settle=8):
    t = res.t
    mask = t >= (attack_start + res.cfg.tau + settle)
    out = {"attack": res.attack_name}
    for c in res.x_true:
        err = res.x_hat[c][mask] - res.x_true[c][mask]
        out[c] = {
            "crosstrack_est_rmse": float(np.sqrt(np.mean(err[:, 1] ** 2))),
            "state_est_rmse": float(np.sqrt(np.mean(np.sum(err ** 2, axis=1)))),
            "true_final_crosstrack": float(abs(res.x_true[c][-1, 1])),
            "true_max_crosstrack": float(np.max(np.abs(res.x_true[c][:, 1]))),
        }
    if res.attacked is not None:
        truth = res.attack_truth; dec = res.attacked
        post = t >= attack_start
        tp = np.sum(dec[post] & truth[post]); fp = np.sum(dec[post] & ~truth[post])
        fn = np.sum(~dec[post] & truth[post])
        prec = tp / (tp + fp) if (tp + fp) else float("nan")
        rec = tp / (tp + fn) if (tp + fn) else float("nan")
        pre = t < attack_start
        far = float(np.mean(dec[pre])) if np.any(pre) else float("nan")
        lat = np.nan
        atk_ch = np.where(np.any(truth, axis=0))[0]
        if atk_ch.size:
            for k in np.where(post)[0]:
                if np.any(dec[k, atk_ch]):
                    lat = float(t[k] - attack_start); break
        out["detection"] = dict(precision=float(prec), recall=float(rec),
                                false_alarm_rate=far, latency_s=lat,
                                attacked_channels=atk_ch.tolist())
    return out


def _believed_track(res, model, conf):
    """Absolute (along, cross) track the estimator BELIEVES it is on."""
    U = model.p.U
    N = U * res.t + res.x_hat[conf][:, 0]
    E = res.x_hat[conf][:, 1]
    return N, E


def _true_track(res, model, conf):
    U = model.p.U
    return U * res.t + res.x_true[conf][:, 0], res.x_true[conf][:, 1]


