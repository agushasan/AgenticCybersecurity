# ============================================================================ #
#  10. Maneuvering example: route bird's-eye                                   #
# ============================================================================ #
def fig_route_birdseye(res, model, hazard_E=70.0, attack_start=None, fname=None,
                       title=None):
    """
    Bird's-eye of the vessel maneuvering along a curving predefined fairway.
    The navigable channel is the ±hazard_E corridor about the reference
    centreline E_ref(N); outside is grounding hazard.  Shows the secure and
    naive true hull tracks and, for the naive filter, the believed (ghost)
    track that keeps it hugging the centreline while the real hull is dragged
    into the bank.
    """
    U = model.p.U
    N = U * res.t
    Eref = res.E_ref
    fig, ax = plt.subplots(figsize=(7.0, 8.4))

    # hazard (land) fill, then navigable channel on top
    xlo, xhi = Eref.min() - hazard_E - 160, Eref.max() + hazard_E + 160
    ax.fill_betweenx(N, xlo, xhi, color=P["hazard"], alpha=0.085, lw=0)
    ax.fill_betweenx(N, Eref - hazard_E, Eref + hazard_E, color=P["secure"],
                     alpha=0.085, lw=0, label="navigable channel")
    ax.plot(Eref - hazard_E, N, color=P["hazard"], lw=1.2, alpha=0.7)
    ax.plot(Eref + hazard_E, N, color=P["hazard"], lw=1.2, alpha=0.7,
            label="channel edge (grounding)")
    ax.plot(Eref, N, color=P["subtle"], lw=1.3, ls=(0, (6, 4)),
            label="planned route (centreline)")

    # secure true track
    if "secure" in res.x_true:
        ax.plot(res.x_true["secure"][:, 1], N, color=P["secure"], lw=2.6,
                label="secure: true hull track", zorder=5)
    # naive true track (time-coloured) + believed ghost + deception fill
    if "naive" in res.x_true:
        En = res.x_true["naive"][:, 1]; Eb = res.x_hat["naive"][:, 1]
        ax.fill_betweenx(N, En, Eb, color=P["naive"], alpha=0.12, lw=0)
        lc = S.time_colored_line(ax, En, N, res.t, cmap=S.CMAP_TIME, lw=3.0,
                                 zorder=6)
        ax.plot(Eb, N, color=P["believed"], lw=1.6, ls=(0, (2, 2)), zorder=5,
                label="naive: believed track (ghost)")
        ax.scatter([En[-1]], [N[-1]], s=130, color=P["naive"], marker="X",
                   edgecolor="white", linewidth=1.4, zorder=7,
                   label="naive: final hull position")
        cbar = fig.colorbar(lc, ax=ax, fraction=0.035, pad=0.02)
        cbar.set_label("time  [s]", fontsize=10); cbar.ax.tick_params(labelsize=9)

    ax.scatter([Eref[0]], [N[0]], s=60, color=P["ink"], marker="o",
               edgecolor="white", linewidth=1.2, zorder=7, label="transit start")
    if attack_start is not None:
        ka = int(attack_start / model.p.dt)
        if ka < len(N):
            ax.scatter([Eref[ka]], [N[ka]], s=80, color=P["attack"], marker="D",
                       edgecolor="white", linewidth=1.2, zorder=7)
            ax.annotate("attack onset", xy=(Eref[ka], N[ka]), xytext=(20, 0),
                        textcoords="offset points", fontsize=9.5,
                        color=P["attack"], fontweight="bold", va="center",
                        arrowprops=dict(arrowstyle="->", color=P["attack"], lw=1.3))

    ax.set_xlim(xlo, xhi)
    ax.set_xlabel("cross-track East  E  [m]")
    ax.set_ylabel("along-track North  [m]")
    if title:
        ax.set_title(title)
    S.style_legend(ax, loc="upper left", fontsize=9.0)
    return S.finalize(fig, fname)


