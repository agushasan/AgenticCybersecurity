#  7. Monte-Carlo                                                              #
# ============================================================================ #
def fig_mc(mc, fname=None, title=None):
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10.4, 4.1))
    rates = np.array(mc["rates"])
    lm = np.array(mc["latency_mean"]); ls = np.array(mc["latency_std"])
    rm = np.array(mc["recall_mean"]); rs = np.array(mc["recall_std"])
    ax1.fill_between(rates, lm - ls, lm + ls, color=P["secure"], alpha=0.18, lw=0)
    ax1.plot(rates, lm, color=P["secure"], lw=2.2, marker="o", ms=6,
             mec="white", mew=1.2)
    ax1.set_xlabel("GNSS walk-off rate  [m/s]")
    ax1.set_ylabel("detection latency  [s]")
    ax1.set_title("Time-to-detect", fontsize=11.5)
    ax1.annotate("stealthier\n← slower", xy=(rates[0], lm[0]), xytext=(10, -2),
                 textcoords="offset points", fontsize=9, color=P["subtle"])

    ax2.fill_between(rates, np.clip(rm - rs, 0, 1), np.clip(rm + rs, 0, 1),
                     color=P["naive"], alpha=0.18, lw=0)
    ax2.plot(rates, rm, color=P["naive"], lw=2.2, marker="s", ms=6,
             mec="white", mew=1.2)
    ax2.set_ylim(-0.03, 1.03)
    ax2.set_xlabel("GNSS walk-off rate  [m/s]")
    ax2.set_ylabel("attacked-channel recall")
    ax2.set_title("Isolation recall", fontsize=11.5)
    if title:
        fig.suptitle(title, fontsize=12.5, fontweight="bold", y=1.02)
    return S.finalize(fig, fname)


# ============================================================================ #
#  8. Observability / security schematic                                       #
# ============================================================================ #
def fig_observability(model, sec, fname=None, title=None):
    """
    Sensor -> state coverage grid coloured by sensor TYPE, with per-state sensor
    redundancy, how many anchors survive a GNSS common-mode spoof, and the
    sparse-observability margin.  This visualises the core security argument:
    each position axis has only ONE GNSS-independent anchor (radar), so a
    common-mode GNSS spoof leaves exactly one anchor per axis.
    """
    p, n = model.psensors, model.n
    state_lbl = ["δN\nalong", "δE\ncross", "δψ\nhead.", "δu\nsurge",
                 "δv\nsway", "δr\nyaw"]
    Cabs = (np.abs(model.C) > 1e-9)
    group_color = {"GNSS_A": P["attack"], "GNSS_B": P["attack"],
                   "RADAR": P["secure"], "GYROC": P["clean"],
                   "MAG": P["clean"], "FOG": P["clean"],
                   "IMU": P["believed"], "LOG": P["gold"]}

    fig, ax = plt.subplots(figsize=(10.4, 6.8))
    ax.set_xlim(-0.5, n - 0.5); ax.set_ylim(p - 0.5, -0.95)
    for i in range(p):
        for j in range(n):
            if Cabs[i, j]:
                col = group_color.get(model.devices[i], P["subtle"])
                ax.add_patch(Rectangle((j - 0.42, i - 0.42), 0.84, 0.84,
                                       fc=col, ec="white", lw=1.2,
                                       alpha=0.5 if model.gnss_mask[i] else 0.9))
    # GNSS common-mode bracket
    gnss_rows = [i for i in range(p) if model.gnss_mask[i]]
    ax.add_patch(Rectangle((-0.5, min(gnss_rows) - 0.5), n,
                           len(gnss_rows), fill=False, ec=P["attack"],
                           lw=2.0, ls=(0, (4, 2)), zorder=5))

    # per-state redundancy counts (total + GNSS-independent survivors) ON TOP
    for j in range(n):
        total = int(Cabs[:, j].sum())
        surv = int(sum(Cabs[i, j] and not model.gnss_mask[i] for i in range(p)))
        ax.text(j, -0.70, f"{total} sensor{'s' if total > 1 else ''}",
                ha="center", va="center", fontsize=9.0, color=P["ink"],
                fontweight="bold")
        col = P["hazard"] if surv <= 1 else P["clean"]
        ax.text(j, -0.40, f"{surv} survive spoof", ha="center", va="center",
                fontsize=8.4, color=col, fontweight="bold")

    ax.set_xticks(range(n)); ax.set_xticklabels(state_lbl, fontsize=8.6)
    ax.set_yticks(range(p)); ax.set_yticklabels(model.names, fontsize=9.4)
    ax.tick_params(length=0); ax.grid(False)
    for s in ax.spines.values():
        s.set_visible(False)

    # right-hand annotation column (axes-fraction coords, never clipped)
    ax.text(1.04, 0.82, "GNSS common-mode\n(all spoofed together)",
            transform=ax.transAxes, va="center", ha="left", fontsize=8.8,
            color=P["attack"], fontweight="bold")
    txt = (f"Security margin\n"
           f"  max $s$-sparse obs.  $\\bar s$ = {sec['smax_obs']}\n"
           f"  certified  $s_{{max}}$ = {sec['s_max']}\n"
           f"  2s-restr. eig.  $\\delta_{{2s}}$ = {float(sec['delta_2s']):.2f}\n\n"
           f"A GNSS common-mode spoof\n"
           f"corrupts 4 channels ($\\gg s_{{max}}$),\n"
           f"but each position axis keeps\n"
           f"its ONE radar anchor, so the\n"
           f"surviving set stays observable\n"
           f"and the SSE still recovers.")
